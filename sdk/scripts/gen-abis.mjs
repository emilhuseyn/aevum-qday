// Regenerates src/abis.ts and src/deployments.ts from the Foundry build (contracts/out) and
// contracts/deployments/*.json, so the SDK never drifts from the deployed contracts.
//   cd contracts && forge build && cd ../sdk && pnpm gen:abis
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "..", "..", "contracts");
const out = join(contracts, "out");

const CONTRACTS = {
  invoicePayAbi: "InvoicePay.sol/InvoicePay.json",
  payeeRegistryAbi: "PayeeRegistry.sol/PayeeRegistry.json",
  payeeGuardAccountAbi: "PayeeGuardAccount.sol/PayeeGuardAccount.json",
  payeeGuardAccountFactoryAbi: "PayeeGuardAccountFactory.sol/PayeeGuardAccountFactory.json",
  payeeGuardPaymasterAbi: "PayeeGuardPaymaster.sol/PayeeGuardPaymaster.json",
  identityRegistryAbi: "IdentityRegistryUpgradeable.sol/IdentityRegistryUpgradeable.json",
};

let abis = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit.\n\n";
for (const [name, path] of Object.entries(CONTRACTS)) {
  const { abi } = JSON.parse(readFileSync(join(out, path), "utf8"));
  abis += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(here, "..", "src", "abis.ts"), abis);

const deployments = {};
for (const file of readdirSync(join(contracts, "deployments"))) {
  const m = /^(\d+)\.json$/.exec(file);
  if (m) deployments[m[1]] = JSON.parse(readFileSync(join(contracts, "deployments", file), "utf8"));
}
writeFileSync(
  join(here, "..", "src", "deployments.ts"),
  "// Generated by scripts/gen-abis.mjs from contracts/deployments. Do not edit.\n\n" +
    `export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);
console.log("wrote src/abis.ts and src/deployments.ts:", Object.keys(CONTRACTS).join(", "), "chains", Object.keys(deployments));
